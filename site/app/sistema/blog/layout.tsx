// Editor routes have their own full-screen layout (BlogEditorClient has its own TopNav)
function isEditorRoute(pathname: string): boolean {
  const after = pathname.slice('/sistema/blog'.length).replace(/^\//, '')
  if (!after || after === 'rascunhos' || after === 'relatorios') return false
  return true
}

export default function BlogSectionLayout({ children }: { children: React.ReactNode }) {
  const pathname = usePathname()

  if (isEditorRoute(pathname)) {
    return <>{children}</>
  }

  return (
    <div className="flex flex-col min-h-screen">
      <TopNav />
      <main className="flex-1 overflow-auto">{children}</main>
      <CornerRadialMenu
        items={BLOG_ITEMS}
        parentItems={SITE_PARENT_ITEMS}
        backHref="/sistema"
        backLabel="Voltar"
      />
    </div>
  )
}
